create or replace function public.bx_enforce_capacity()
returns trigger
language plpgsql
set search_path = public
as $$
declare
  current_total bigint;
begin
  perform pg_advisory_xact_lock(50950000);
  select count(*) into current_total from public.bx_registrations;
  if current_total >= 50000 then
    raise exception 'BX_FOLDER_CAPACITY_REACHED';
  end if;
  return new;
end;
$$;

drop trigger if exists bx_capacity_guard on public.bx_registrations;
create trigger bx_capacity_guard
before insert on public.bx_registrations
for each row execute function public.bx_enforce_capacity();

create or replace function public.bx_assign_group()
returns table(id bigint, name text, url text, capacity integer, assigned_count integer)
language plpgsql
security definer
set search_path = public
as $$
declare
  chosen public.bx_groups%rowtype;
begin
  select * into chosen
  from public.bx_groups
  where enabled = true and assigned_count < capacity
  order by priority asc, id asc
  for update skip locked
  limit 1;

  if chosen.id is null then return; end if;

  update public.bx_groups
  set assigned_count = bx_groups.assigned_count + 1
  where bx_groups.id = chosen.id
  returning bx_groups.id, bx_groups.name, bx_groups.url, bx_groups.capacity, bx_groups.assigned_count
  into id, name, url, capacity, assigned_count;

  return next;
end;
$$;

create or replace function public.bx_rate_limit_hit(
  p_bucket text, p_identity text, p_window_seconds integer, p_limit integer
)
returns boolean
language plpgsql
security definer
set search_path = public
as $$
declare
  w timestamptz;
  n integer;
begin
  w := to_timestamp(floor(extract(epoch from now()) / greatest(1,p_window_seconds)) * greatest(1,p_window_seconds));
  insert into public.bx_rate_limits(bucket, identity, window_start, hits)
  values (p_bucket, p_identity, w, 1)
  on conflict (bucket, identity, window_start)
  do update set hits = bx_rate_limits.hits + 1
  returning hits into n;
  return n <= greatest(1,p_limit);
end;
$$;

create or replace function public.bx_admin_stats()
returns jsonb
language sql
security definer
set search_path = public
as $$
  select jsonb_build_object(
    'total', count(*),
    'male', count(*) filter (where sex = 'male'),
    'female', count(*) filter (where sex = 'female'),
    'today', count(*) filter (where created_at >= date_trunc('day', now())),
    'last7', count(*) filter (where created_at >= now() - interval '7 days'),
    'countries', coalesce((
      select jsonb_agg(jsonb_build_object('country', country, 'count', cnt) order by cnt desc)
      from (
        select country, count(*)::int as cnt
        from public.bx_registrations
        group by country
        order by count(*) desc
        limit 8
      ) c
    ), '[]'::jsonb)
  )
  from public.bx_registrations;
$$;
