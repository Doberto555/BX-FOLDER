create table if not exists public.bx_groups (
  id bigint generated by default as identity primary key,
  name text not null check (char_length(name) between 2 and 80),
  url text not null unique check (url like 'https://chat.whatsapp.com/%'),
  capacity integer not null default 1024 check (capacity between 1 and 100000),
  assigned_count integer not null default 0 check (assigned_count >= 0),
  enabled boolean not null default true,
  priority integer not null default 100,
  created_at timestamptz not null default now()
);

create table if not exists public.bx_registrations (
  id bigint generated by default as identity primary key,
  surname text not null check (char_length(surname) between 2 and 60),
  display_name text not null,
  phone text not null unique check (phone ~ '^[0-9]{8,15}$'),
  sex text not null check (sex in ('male', 'female')),
  country text not null check (char_length(country) between 2 and 80),
  consent_vcf boolean not null default false,
  group_id bigint references public.bx_groups(id) on delete set null,
  created_at timestamptz not null default now()
);

create table if not exists public.bx_settings (
  key text primary key,
  value jsonb not null,
  updated_at timestamptz not null default now()
);

create table if not exists public.bx_removal_requests (
  id bigint generated by default as identity primary key,
  phone text not null check (phone ~ '^[0-9]{8,15}$'),
  reason text not null default '',
  status text not null default 'pending' check (status in ('pending','approved','rejected')),
  created_at timestamptz not null default now()
);

create table if not exists public.bx_rate_limits (
  bucket text not null,
  identity text not null,
  window_start timestamptz not null,
  hits integer not null default 0,
  primary key(bucket, identity, window_start)
);

